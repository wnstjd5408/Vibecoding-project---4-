test('create, edit, and delete a note without leaving the preview', async ({ page }) => {
  await page.goto(previewPath('F5-1d'))
  await page.getByLabel('제목', { exact: true }).fill('합성 노트 테스트')
  await page.getByLabel('네트워크', { exact: true }).check()
  await page.getByLabel('학습일', { exact: true }).fill('2026-10-28')
  await page.getByLabel('본문', { exact: true }).fill('자동 검증을 위한 합성 본문입니다.')
  await page.getByRole('button', { name: '저장', exact: true }).click()
  const row = page.getByRole('row').filter({ hasText: '합성 노트 테스트' })
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: '수정' }).click()
  await expect(page.getByLabel('본문', { exact: true })).toHaveValue('자동 검증을 위한 합성 본문입니다.')
  await page.getByLabel('제목', { exact: true }).fill('수정된 합성 노트')
  await page.getByRole('button', { name: '저장', exact: true }).click()
  await page.getByRole('row').filter({ hasText: '수정된 합성 노트' }).getByRole('button', { name: '삭제' }).click()
  await page.getByRole('button', { name: '삭제하기', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: '수정된 합성 노트' })).toHaveCount(0)
})

