import { expect, test } from '@playwright/test'
import { frameViewport, previewPath, screens } from '../src/mockup/screens.ts'

for (const [id, name] of screens) {
  test(`${id} renders without runtime errors or horizontal overflow`, async ({ page }, testInfo) => {
    const errors: string[] = []
    page.on('pageerror', (error) => errors.push(error.message))
    page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
    await page.setViewportSize(frameViewport(id))
    await page.goto(`${previewPath(id)}?clean=true`)
    await expect(page).toHaveTitle(`${name} · CS 학습 노트`)
    await expect(page.locator('h1')).toHaveCount(1)
    await page.evaluate(() => document.fonts.ready)
    expect(await page.evaluate(() => document.fonts.check('16px Pretendard'))).toBe(true)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    const path = testInfo.outputPath(`${id}.png`)
    await page.screenshot({ path, fullPage: true })
    await testInfo.attach(id, { path, contentType: 'image/png' })
    expect(errors).toEqual([])
  })
}

